// Integration smoke test against the local Worker only. Creates isolated QA records.
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const origin = process.env.TEST_ORIGIN || 'http://127.0.0.1:5173';
assert.ok(['127.0.0.1','localhost'].includes(new URL(origin).hostname), 'Only loopback testing is allowed');
const vars = Object.fromEntries(readFileSync('.dev.vars','utf8').trim().split(/\r?\n/).filter(s=>s.includes('=')).map(s=>[s.slice(0,s.indexOf('=')),s.slice(s.indexOf('=')+1)]));
const path = '.sites-runtime/test-owner.json';
const owner = existsSync(path) ? JSON.parse(readFileSync(path,'utf8')) : {name:'Local QA Owner',email:vars.OWNER_EMAIL,password:randomBytes(24).toString('base64url')};
if (!existsSync(path)) writeFileSync(path,JSON.stringify(owner));
async function call(path,method='GET',data,session='',expected=200) {
  const res=await fetch(origin+path,{method,headers:{Origin:origin,'X-Requested-With':'Relay','Content-Type':'application/json',...(session?{Cookie:session}:{})},...(data===undefined?{}:{body:JSON.stringify(data)})});
  const body=await res.json();
  assert.equal(res.status,expected,`${method} ${path}: ${JSON.stringify(body)}`);
  return {body,cookie:res.headers.get('set-cookie')?.split(';')[0]??''};
}
assert.equal((await call('/api/session')).body.user,null);
await call('/api/products','GET',undefined,'',401);
const attempt=await fetch(origin+'/api/auth/login',{method:'POST',headers:{Origin:origin,'X-Requested-With':'Relay','Content-Type':'application/json'},body:JSON.stringify({email:owner.email,password:owner.password})});
let ownerCookie;
if(attempt.ok) ownerCookie=attempt.headers.get('set-cookie').split(';')[0];
else ownerCookie=(await call('/api/auth/bootstrap','POST',{...owner,setupToken:vars.OWNER_SETUP_TOKEN},'',201)).cookie;
const suffix=randomBytes(5).toString('hex');
const signup={name:'Local QA Client',email:`qa-${suffix}@example.test`,password:randomBytes(24).toString('base64url')};
const registered=await call('/api/auth/register','POST',signup,'',201);
const clientCookie=registered.cookie, clientId=registered.body.user.id;
assert.equal(registered.body.user.status,'pending');
await call('/api/products','GET',undefined,clientCookie,403);
await call('/api/accounts','GET',undefined,clientCookie,403);
const category=(await call('/api/categories','POST',{name:`QA ${suffix}`},ownerCookie,201)).body.category;
const product=(await call('/api/products','POST',{sku:`QA-${suffix}`,name:'QA case',category:category.name,unit:'Case',priceCents:2500,stock:100,reorderLevel:5},ownerCookie,201)).body.product;
await call(`/api/accounts/${clientId}`,'PATCH',{status:'approved'},ownerCookie);
await call('/api/products','GET',undefined,clientCookie);
await call('/api/categories','POST',{name:'Client forbidden'},clientCookie,403);
await call(`/api/products/${product.id}`,'PATCH',{priceCents:1},clientCookie,403);
await call('/api/orders','POST',{items:[{productId:product.id,quantity:12}],fulfillmentMethod:'delivery'},clientCookie,400);
const order=(await call('/api/orders','POST',{items:[{productId:product.id,quantity:12}],fulfillmentMethod:'pickup'},clientCookie,201)).body.order;
assert.equal(order.totalCents,30000); assert.equal(order.deliveryAddress,'');
assert.ok((await call('/api/orders','GET',undefined,ownerCookie)).body.orders.some(o=>o.id===order.id));
await call(`/api/orders/${order.id}`,'PATCH',{status:'confirmed'},ownerCookie);
await call(`/api/orders/${order.id}`,'PATCH',{status:'delivered'},ownerCookie);
assert.equal((await call('/api/orders','GET',undefined,clientCookie)).body.orders.find(o=>o.id===order.id).status,'delivered');
await call(`/api/accounts/${clientId}`,'PATCH',{status:'rejected'},ownerCookie);
await call('/api/products','GET',undefined,clientCookie,401);
await call('/api/auth/login','POST',{email:signup.email,password:signup.password},'',403);
await call(`/api/products/${product.id}`,'DELETE',undefined,ownerCookie);
await call('/api/auth/logout','POST',{},ownerCookie);
await call('/api/products','GET',undefined,ownerCookie,401);
console.log('PASS: actual Worker password hashing, sessions, pending/approval/revocation, admin categories/products, bulk pickup order and manager completion.');
